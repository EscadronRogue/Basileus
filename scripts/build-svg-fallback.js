// scripts/build-svg-fallback.js - regenerates render/svgAssets.js from assets/*.svg.
//
// The renderer fetches the SVG files directly and only imports the embedded
// copies when that fetch fails, so the two must stay identical. Run
// `npm run build:svg-fallback` after editing any file in assets/*.svg;
// render/svgAssets.test.js fails when they drift apart.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');

export const SVG_FALLBACK_SOURCES = Object.freeze({
  MAP_BACKGROUND_SVG: 'assets/map.svg',
  HITZONES_SVG: 'assets/hitzones.svg',
  HITZONES_COMPACT_SVG: 'assets/hitzones-compact.svg',
  ORIGIN_SVG: 'assets/origin.svg',
});

export const SVG_FALLBACK_MODULE = 'render/svgAssets.js';

export function buildSvgFallbackSource(root = projectRoot) {
  const lines = [
    '// render/svgAssets.js - GENERATED by scripts/build-svg-fallback.js; do not edit.',
    '// Embedded copies of assets/*.svg, loaded lazily only when fetching them fails.',
  ];
  for (const [name, relativePath] of Object.entries(SVG_FALLBACK_SOURCES)) {
    const text = readFileSync(resolve(root, relativePath), 'utf8');
    lines.push(`export const ${name} = ${JSON.stringify(text)};`);
  }
  return `${lines.join('\n')}\n`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  writeFileSync(resolve(projectRoot, SVG_FALLBACK_MODULE), buildSvgFallbackSource());
  console.log(`Wrote ${SVG_FALLBACK_MODULE}`);
}
